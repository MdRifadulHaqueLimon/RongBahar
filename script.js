function addToCart(id, silent) {
  const item = cart.find(c => c.id === id);
  if (item) item.qty++;
  else cart.push({id, qty: 1});
  updateCartUI();
  if (!silent) showToast(t('toastAdded'));
}

function buyNow(id) {
  addToCart(id, true);
  showToast(t('toastBuyNow'));
  toggleCart(true);
}

function changeQty(id, delta) {
  const item = cart.find(c => c.id === id);
  if (!item) return;
  item.qty += delta;
  if (item.qty <= 0) cart = cart.filter(c => c.id !== id);
  updateCartUI();
}

function removeFromCart(id) {
  cart = cart.filter(c => c.id !== id);
  updateCartUI();
}

function cartTotal() {
  return cart.reduce((sum, c) => {
    const p = PRODUCTS.find(x => x.id === c.id);
    return sum + (p ? p.price * c.qty : 0);
  }, 0);
}

function updateCartUI() {
  const badge = document.getElementById('cartBadge');
  const count = cart.reduce((s, c) => s + c.qty, 0);
  badge.style.display = count ? 'flex' : 'none';
  badge.textContent = count;

  const body = document.getElementById('cartBody');
  const checkoutBtn = document.getElementById('checkoutBtn');
  checkoutBtn.disabled = cart.length === 0;

  if (cart.length === 0) {
    body.innerHTML = `<div class="empty-cart">
      <svg width="52" height="52" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6"><circle cx="8" cy="21" r="1"/><circle cx="19" cy="21" r="1"/><path d="M2.05 2.05h2l2.66 12.42a2 2 0 0 0 2 1.58h9.78a2 2 0 0 0 2-1.58l1.65-7.42H5.12"/></svg>
      <div>${t('cartEmpty')}</div>
    </div>`;
  } else {
    body.innerHTML = cart.map(c => {
      const p = PRODUCTS.find(x => x.id === c.id);
      if (!p) return '';
      const displayName = currentLang === 'bn' && p.nameBn ? p.nameBn : p.name;
      return `
      <div class="cart-item">
        <img src="${p.img}" alt="${displayName}">
        <div class="info">
          <div class="cname">${displayName}</div>
          <div class="cprice num">${money(p.price)}</div>
          <div class="qty-row">
            <button class="qty-btn" onclick="changeQty(${p.id},-1)">−</button>
            <span class="qty-val">${c.qty}</span>
            <button class="qty-btn" onclick="changeQty(${p.id},1)">+</button>
            <button class="remove-btn" onclick="removeFromCart(${p.id})" title="${t('remove')}">
              <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M3 6h18"/><path d="M8 6V4a2 2 0 0 1 2-2h4a2 2 0 0 1 2 2v2"/><path d="M19 6l-1 14a2 2 0 0 1-2 2H8a2 2 0 0 1-2-2L5 6"/></svg>
            </button>
          </div>
        </div>
      </div>`;
    }).join('');
  }
  document.getElementById('cartTotal').textContent = money(cartTotal());
}

