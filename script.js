function submitSignin(e) {
  e.preventDefault();
  const msg = document.getElementById('signinMsg');
  const input = document.getElementById('siEmail').value.trim();
  const password = document.getElementById('siPassword').value;

  const user = users.find(u => (u.email === input || u.phone === input) && u.password === password);
  if (user) {
    currentUser = { name: user.name, phone: user.phone, email: user.email };
    renderUserArea();
    toggleAuth(false);
    showToast(t('welcome') + ', ' + user.name.split(' ')[0] + '! 🎉');
    msg.textContent = '';
  } else {
    msg.textContent = t('invalidCredentials');
    msg.className = 'form-msg err';
  }
}

function submitSignup(e) {
  e.preventDefault();
  const msg = document.getElementById('signupMsg');
  const name = document.getElementById('suName').value.trim();
  const phone = document.getElementById('suPhone').value.trim();
  const email = document.getElementById('suEmail').value.trim();
  const password = document.getElementById('suPassword').value;
  const confirm = document.getElementById('suConfirmPassword').value;

  if (password !== confirm) {
    msg.textContent = t('passwordMismatch');
    msg.className = 'form-msg err';
    return;
  }
  if (users.find(u => u.email === email)) {
    msg.textContent = t('emailExists');
    msg.className = 'form-msg err';
    return;
  }
  if (users.find(u => u.phone === phone)) {
    msg.textContent = t('phoneExists');
    msg.className = 'form-msg err';
    return;
  }

  users.push({ name, phone, email, password });
  currentUser = { name, phone, email };
  renderUserArea();
  toggleAuth(false);
  showToast(t('welcome') + ', ' + name.split(' ')[0] + '! 🎉');
  document.getElementById('signupForm').reset();
}

