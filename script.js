function submitOrder(e) {
  e.preventDefault();
  const btn = document.getElementById('orderSubmitBtn');
  const msg = document.getElementById('formMsg');

  const orderLines = cart.map(c => {
    const p = PRODUCTS.find(x => x.id === c.id);
    const displayName = currentLang === 'bn' && p.nameBn ? p.nameBn : p.name;
    return `${displayName} x${c.qty} = ${money(p.price * c.qty)}`;
  }).join('\n');

  const payload = {
    _subject: `🛍️ New Order — RongBahar`,
    'Customer Name': document.getElementById('coName').value.trim(),
    'Phone': document.getElementById('coPhone').value.trim(),
    'Email': document.getElementById('coEmail').value.trim(),
    'Address': document.getElementById('coAddress').value.trim(),
    'Note': document.getElementById('coNote').value.trim() || '—',
    'Ordered Products': orderLines,
    'Total Price': money(cartTotal()),
    _captcha: 'false',
    _template: 'table'
  };

  btn.disabled = true;
  btn.textContent = t('sending');
  msg.textContent = '';
  msg.className = 'form-msg';

  fetch(`https://formsubmit.co/ajax/${OWNER_EMAIL}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'Accept': 'application/json' },
    body: JSON.stringify(payload)
  })
  .then(res => res.json())
  .then(() => {
    msg.textContent = t('orderSuccess');
    msg.classList.add('ok');
    cart = [];
    updateCartUI();
    btn.textContent = t('confirmOrder');
    btn.disabled = false;
    setTimeout(() => {
      toggleCheckout(false);
      document.getElementById('checkoutForm').reset();
      msg.textContent = '';
    }, 2200);
  })
  .catch(() => {
    msg.textContent = t('orderError');
    msg.classList.add('err');
    btn.textContent = t('confirmOrder');
    btn.disabled = false;
  });
}

