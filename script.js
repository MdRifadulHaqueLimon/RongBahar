let currentSlide = 0;
let slideInterval;
const totalSlides = 4;

function initSlider() {
  const dotsContainer = document.getElementById('sliderDots');
  dotsContainer.innerHTML = '';
  for (let i = 0; i < totalSlides; i++) {
    const dot = document.createElement('button');
    dot.className = 'dot' + (i === 0 ? ' active' : '');
    dot.onclick = () => goToSlide(i);
    dotsContainer.appendChild(dot);
  }
  startSlideTimer();
  const slider = document.getElementById('heroSlider');
  slider.addEventListener('mouseenter', stopSlideTimer);
  slider.addEventListener('mouseleave', startSlideTimer);
  slider.addEventListener('touchstart', stopSlideTimer, {passive:true});
  slider.addEventListener('touchend', startSlideTimer, {passive:true});
}

function goToSlide(index) {
  currentSlide = index;
  const track = document.getElementById('sliderTrack');
  track.style.transform = 'translateX(-' + (index * 100) + '%)';
  document.querySelectorAll('.slider-dots .dot').forEach((d, i) => {
    d.classList.toggle('active', i === index);
  });
  document.querySelectorAll('.slide').forEach((s, i) => {
    s.classList.toggle('active', i === index);
  });
}

function nextSlide() {
  goToSlide((currentSlide + 1) % totalSlides);
}

function prevSlide() {
  goToSlide((currentSlide - 1 + totalSlides) % totalSlides);
}

function startSlideTimer() {
  stopSlideTimer();
  slideInterval = setInterval(nextSlide, 4500);
}

function stopSlideTimer() {
  clearInterval(slideInterval);
}

